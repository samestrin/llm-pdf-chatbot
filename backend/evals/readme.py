"""The eval's score table in the README: the newest results file in `evals/results/`
(by its date), rendered as `evals.run` prints it, between the README's markers.

    cd backend && uv run python -m evals.readme           # check: exit 1 if the README differs
    cd backend && uv run python -m evals.readme --write   # rewrite the README's table

CI runs the check in the tests, before its own subset run writes a results file. With no
results file, the README shows `NOT_PUBLISHED` instead of a table.
"""

import argparse
import difflib
import json
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from evals.run import RESULTS, table
from evals.score import Scores
from evals.sources import EVALS

README = EVALS.parent.parent / "README.md"
BEGIN = (
    "<!-- eval-score:begin (generated by `cd backend && uv run python -m evals.readme --write`) -->"
)
END = "<!-- eval-score:end -->"
NOT_PUBLISHED = (
    "The evaluation score table is not published yet: it will be added here from the "
    "owner's first full run."
)


def newest_results(results_dir: Path) -> Path | None:
    """The results file with the latest date in its name, or None when there is none."""
    files = sorted(results_dir.glob("[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9].json"))
    return files[-1] if files else None


def score_block(results: dict[str, Any] | None) -> str:
    """What goes between the markers for a results file's contents."""
    if results is None:
        return NOT_PUBLISHED
    day = results["date"]
    how = ", judged by the same model" if results["judge"] else ""
    return (
        f"From `backend/evals/results/{day}.json`, the {results['run']} run of {day}: "
        f"{results['questions']} questions on {len(results['pdfs'])} PDFs, "
        f"model `{results['model']}`{how}.\n\n" + table(Scores.from_json(results["scores"]))
    )


def _span(text: str) -> tuple[int, int] | None:
    """Where the block between the markers starts and ends in `text`."""
    begin = text.find(BEGIN)
    end = text.find(END, begin)
    if begin < 0 or end < 0:
        return None
    return begin + len(BEGIN), end


def with_block(text: str, block: str) -> str:
    span = _span(text)
    if span is None:
        raise ValueError(f"the README has no {BEGIN} ... {END} markers")
    start, end = span
    return f"{text[:start]}\n{block}\n{text[end:]}"


def check(readme: Path, results_dir: Path) -> list[str]:
    """The problems with the README's block against the newest results file; [] if none."""
    text = readme.read_text()
    span = _span(text)
    if span is None:
        return [f"{readme} has no {BEGIN} ... {END} markers"]
    newest = newest_results(results_dir)
    expected = score_block(json.loads(newest.read_text()) if newest else None)
    actual = text[span[0] : span[1]].strip("\n")
    if actual == expected:
        return []
    source = newest.name if newest else "no results file"
    diff = difflib.unified_diff(
        actual.splitlines(), expected.splitlines(), "README.md", source, lineterm=""
    )
    return [f"{readme}'s score table differs from {source}:", *diff]


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m evals.readme", description=__doc__.split("\n")[0]
    )
    parser.add_argument("--write", action="store_true", help="rewrite the README's table")
    parser.add_argument("--readme", type=Path, default=README, help=argparse.SUPPRESS)
    parser.add_argument("--results", type=Path, default=RESULTS, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)

    if args.write:
        newest = newest_results(args.results)
        block = score_block(json.loads(newest.read_text()) if newest else None)
        try:
            text = with_block(args.readme.read_text(), block)
        except ValueError as exc:
            print(f"{args.readme}: {exc}", file=sys.stderr)
            return 1
        args.readme.write_text(text)
        return 0
    problems = check(args.readme, args.results)
    if problems:
        print("\n".join(problems), file=sys.stderr)
        print("Run `cd backend && uv run python -m evals.readme --write`.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
