"""Upload PDFs, report their ingestion status, and delete them.

There is no auth on these routes: the app is local and single-user.

A stored PDF lives at `<UPLOAD_DIR>/<id>.pdf`, where `id` is generated by the
server. The client's file name is kept for display only and never touches the
file system.
"""

import os
import re
import tempfile
import uuid
from dataclasses import dataclass
from pathlib import Path
from typing import Annotated

import pymupdf
from fastapi import APIRouter, File, HTTPException, Request, Response, UploadFile
from fastapi import Path as PathParam
from sqlalchemy import Engine, delete, insert, select
from sqlalchemy.exc import IntegrityError

from app.db import collections, documents, ingestion_status
from app.db import pages as page_table

DEFAULT_UPLOAD_DIR = "./data/uploads"
DEFAULT_MAX_UPLOAD_MB = 50
DEFAULT_MAX_PDF_PAGES = 500
CHUNK_BYTES = 1024 * 1024
NO_AUTH_NOTE = "There is no auth: the app is local and single-user."


@dataclass(frozen=True)
class Limits:
    upload_dir: Path
    max_upload_bytes: int
    max_pdf_pages: int

    @classmethod
    def from_env(cls) -> "Limits":
        return cls(
            upload_dir=Path(os.environ.get("UPLOAD_DIR", DEFAULT_UPLOAD_DIR)),
            max_upload_bytes=int(os.environ.get("MAX_UPLOAD_MB", DEFAULT_MAX_UPLOAD_MB))
            * 1024
            * 1024,
            max_pdf_pages=int(os.environ.get("MAX_PDF_PAGES", DEFAULT_MAX_PDF_PAGES)),
        )


def display_name(client_name: str | None) -> str:
    """The last component of the client's name, for display; never a path."""
    name = re.split(r"[/\\]", client_name or "")[-1].strip()
    return name[:255] or "upload.pdf"


def stored_path(limits: Limits, document_id: str) -> Path:
    return limits.upload_dir / f"{document_id}.pdf"


def get_or_create_collection(engine: Engine, name: str) -> int:
    query = select(collections.c.id).where(collections.c.name == name)
    with engine.begin() as conn:
        if (found := conn.execute(query).scalar()) is not None:
            return found
    try:
        with engine.begin() as conn:
            return conn.execute(
                insert(collections).values(name=name).returning(collections.c.id)
            ).scalar_one()
    except IntegrityError:
        # A concurrent upload created it first.
        with engine.begin() as conn:
            return conn.execute(query).scalar_one()


router = APIRouter()


@router.post(
    "/collections/{collection}/documents",
    status_code=201,
    description=(
        "Upload a PDF into the named collection, creating the collection if it is new, and "
        "queue it for ingestion (reading, keyword index, embeddings) in the background. "
        f"Non-PDF content and PDFs over the page limit return 422; files over the size limit "
        f"return 413. {NO_AUTH_NOTE}"
    ),
)
def upload_document(
    request: Request,
    collection: Annotated[str, PathParam(min_length=1, max_length=200)],
    file: Annotated[UploadFile, File()],
) -> dict:
    limits: Limits = request.app.state.limits
    engine = request.app.state.engine
    limits.upload_dir.mkdir(parents=True, exist_ok=True)

    document_id = uuid.uuid4().hex
    fd, tmp_name = tempfile.mkstemp(dir=limits.upload_dir, prefix=".upload-", suffix=".part")
    tmp_path = Path(tmp_name)
    try:
        size = 0
        with os.fdopen(fd, "wb") as out:
            while chunk := file.file.read(CHUNK_BYTES):
                if size == 0 and not chunk.startswith(b"%PDF"):
                    raise HTTPException(422, "file is not a PDF")
                size += len(chunk)
                if size > limits.max_upload_bytes:
                    raise HTTPException(
                        413, f"file is larger than {limits.max_upload_bytes // (1024 * 1024)} MB"
                    )
                out.write(chunk)
        if size == 0:
            raise HTTPException(422, "file is not a PDF")

        try:
            with pymupdf.open(tmp_path, filetype="pdf") as pdf:
                pages = pdf.page_count
        except Exception as exc:
            raise HTTPException(422, "file could not be read as a PDF") from exc
        if pages == 0:
            raise HTTPException(422, "PDF has no pages")
        if pages > limits.max_pdf_pages:
            raise HTTPException(422, f"PDF has {pages} pages; the limit is {limits.max_pdf_pages}")

        filename = display_name(file.filename)
        final_path = stored_path(limits, document_id)
        collection_id = get_or_create_collection(engine, collection)
        try:
            with engine.begin() as conn:
                conn.execute(
                    insert(documents).values(
                        id=document_id,
                        collection_id=collection_id,
                        filename=filename,
                        size_bytes=size,
                        page_count=pages,
                    )
                )
                conn.execute(
                    insert(ingestion_status).values(
                        document_id=document_id, state="queued", pages_total=pages
                    )
                )
                # Inside the transaction: if the rename fails, the row is rolled back.
                tmp_path.replace(final_path)
        except BaseException:
            # The commit failed after the rename: no row points at the file, so remove it.
            final_path.unlink(missing_ok=True)
            raise
    finally:
        tmp_path.unlink(missing_ok=True)

    request.app.state.worker.submit(document_id)
    return {
        "id": document_id,
        "collection": collection,
        "filename": filename,
        "pages": pages,
        "size_bytes": size,
        "status": "queued",
    }


@router.get(
    "/documents/{document_id}/status",
    description=(
        "Where a document's ingestion is: its state (`queued`, `processing`, `ready`, or "
        "`failed` with the reason), how many pages were read, and, once its pages are read, "
        "each page with the method that read it (`text_layer` or `tesseract` from OCR, "
        "`pymupdf` from the text layer fallback) and why OCR failed on it, if it did. Pages "
        f"no method could read are listed under `failures` with the reason. {NO_AUTH_NOTE}"
    ),
)
def document_status(request: Request, document_id: str) -> dict:
    with request.app.state.engine.connect() as conn:
        row = conn.execute(
            select(documents.c.filename, ingestion_status)
            .join(ingestion_status, ingestion_status.c.document_id == documents.c.id)
            .where(documents.c.id == document_id)
        ).first()
        if row is None:
            raise HTTPException(404, "document not found")
        page_rows = conn.execute(
            select(
                page_table.c.page, page_table.c.method, page_table.c.ocr_error, page_table.c.error
            )
            .where(page_table.c.document_id == document_id)
            .order_by(page_table.c.page)
        ).all()
    failures = [
        {"page": p.page, "reason": p.error, "ocr_error": p.ocr_error}
        for p in page_rows
        if p.error is not None
    ]
    return {
        "id": document_id,
        "filename": row.filename,
        "state": row.state,
        "error": row.error,
        "pages_total": row.pages_total,
        "pages_read": row.pages_read,
        "pages_failed": len(failures),
        "chunks_total": row.chunks_total,
        "chunks_embedded": row.chunks_embedded,
        "updated_at": row.updated_at,
        "pages": [
            {"page": p.page, "method": p.method, "ocr_error": p.ocr_error, "error": p.error}
            for p in page_rows
        ],
        "failures": failures,
    }


@router.delete(
    "/documents/{document_id}",
    status_code=204,
    description=(
        "Delete a document: its stored file, its row, and (by foreign-key cascade) every row "
        f"derived from it. {NO_AUTH_NOTE}"
    ),
)
def delete_document(request: Request, document_id: str) -> Response:
    limits: Limits = request.app.state.limits
    with request.app.state.engine.begin() as conn:
        deleted = conn.execute(delete(documents).where(documents.c.id == document_id)).rowcount
        if not deleted:
            raise HTTPException(404, "document not found")
        # The id matched a row, so it is one we generated and safe in a path. Unlinking inside
        # the transaction means a file that cannot be removed leaves its row in place too.
        stored_path(limits, document_id).unlink(missing_ok=True)
    return Response(status_code=204)
