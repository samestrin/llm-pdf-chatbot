"""Upload PDFs, report their ingestion status, read them back, and delete them.

There are no accounts. Outside a public demo every collection is shared. In a public demo
a collection belongs to the session that made it (`app.session`): another session's
collection or document is not found, and the shared sample can be read but not changed.

A stored PDF lives at `<UPLOAD_DIR>/<id>.pdf`, where `id` is generated by the
server. The client's file name is kept for display only and never touches the
file system.
"""

import os
import re
import tempfile
import uuid
from dataclasses import dataclass
from pathlib import Path
from typing import Annotated

import pymupdf
from fastapi import APIRouter, Depends, File, HTTPException, Request, Response, UploadFile
from fastapi import Path as PathParam
from fastapi.responses import FileResponse
from pydantic import BaseModel
from sqlalchemy import Engine, delete, exists, insert, select
from sqlalchemy.engine import Connection
from sqlalchemy.exc import IntegrityError

from app.credentials import Credentials, request_credentials
from app.db import SHARED_OWNER, collections, documents, ingestion_status
from app.db import pages as page_table
from app.session import current_session, find_collection, require_owner, visible_owners

DEFAULT_UPLOAD_DIR = "./data/uploads"
DEFAULT_MAX_UPLOAD_MB = 50
DEFAULT_MAX_PDF_PAGES = 500
CHUNK_BYTES = 1024 * 1024
NO_AUTH_NOTE = (
    "There is no auth and there are no accounts. In a public demo a collection belongs to the "
    "browser session that made it: another session's collection or document returns 404, and "
    "the shared sample is read-only (403)."
)
DELETED = {"description": "Deleted; no body"}


class ErrorDetail(BaseModel):
    """The body of a 404 or 409: FastAPI's `HTTPException` sends its detail as this."""

    detail: str


def error_response(description: str) -> dict:
    """An error response in the spec, with the body it is sent with."""
    return {"description": description, "model": ErrorDetail}


@dataclass(frozen=True)
class Limits:
    upload_dir: Path
    max_upload_bytes: int
    max_pdf_pages: int

    @classmethod
    def from_env(cls) -> "Limits":
        return cls(
            upload_dir=Path(os.environ.get("UPLOAD_DIR", DEFAULT_UPLOAD_DIR)),
            max_upload_bytes=int(os.environ.get("MAX_UPLOAD_MB", DEFAULT_MAX_UPLOAD_MB))
            * 1024
            * 1024,
            max_pdf_pages=int(os.environ.get("MAX_PDF_PAGES", DEFAULT_MAX_PDF_PAGES)),
        )


def display_name(client_name: str | None) -> str:
    """The last component of the client's name, for display; never a path."""
    name = re.split(r"[/\\]", client_name or "")[-1].strip()
    return name[:255] or "upload.pdf"


def stored_path(limits: Limits, document_id: str) -> Path:
    return limits.upload_dir / f"{document_id}.pdf"


def get_or_create_collection(
    engine: Engine,
    name: str,
    owner: str = SHARED_OWNER,
    embedding: tuple[str | None, str | None] = (None, None),
) -> int:
    """The owner's collection of this name, made with `embedding` (its preset and embedding
    model) when it is new."""
    query = select(collections.c.id).where(
        collections.c.name == name, collections.c.session_id == owner
    )
    with engine.begin() as conn:
        if (found := conn.execute(query).scalar()) is not None:
            return found
    preset, model = embedding
    try:
        with engine.begin() as conn:
            return conn.execute(
                insert(collections)
                .values(name=name, session_id=owner, embedding_preset=preset, embedding_model=model)
                .returning(collections.c.id)
            ).scalar_one()
    except IntegrityError:
        # A concurrent upload created it first.
        with engine.begin() as conn:
            return conn.execute(query).scalar_one()


def check_embedding(request: Request, found, credentials: Credentials | None, action: str):
    """A 409 with the plain message when the request's preset or embedding model is not the
    one the collection was embedded with; its vectors could not be compared. A collection
    embedded with the server's own model records no preset and is not checked."""
    if found.embedding_preset is None:
        return
    preset = credentials.preset if credentials else None
    if (
        preset is not None
        and preset.id == found.embedding_preset
        and preset.embedding_model == found.embedding_model
    ):
        return
    recorded = request.app.state.presets.get(found.embedding_preset)
    label = recorded.label if recorded else found.embedding_preset
    raise HTTPException(
        409,
        f"This collection was embedded with {found.embedding_model or 'no embedding model'}; "
        f"switch back to {label} to {action}",
    )


def _upload_collection(
    request: Request, session: str, name: str, credentials: Credentials | None
) -> int:
    """The session's collection to upload into, made if it is new; a 403 for the sample and
    a 409 for another preset or embedding model."""
    engine = request.app.state.engine
    with engine.connect() as conn:
        found = find_collection(conn, session, name)
    if found is not None:
        require_owner(session, found.session_id)
    preset = credentials.preset if credentials else None
    embedding = (preset.id, preset.embedding_model) if preset else (None, None)
    collection_id = get_or_create_collection(engine, name, session, embedding)
    with engine.connect() as conn:
        found = conn.execute(
            select(collections.c.embedding_preset, collections.c.embedding_model).where(
                collections.c.id == collection_id
            )
        ).first()
    if found is not None:
        check_embedding(request, found, credentials, "add to it")
    return collection_id


def visible_documents(session: str):
    """A where-clause: the document is in a collection the session may read."""
    return documents.c.collection_id.in_(
        select(collections.c.id).where(collections.c.session_id.in_(visible_owners(session)))
    )


router = APIRouter()


@router.post(
    "/collections/{collection}/documents",
    status_code=201,
    description=(
        "Upload a PDF into the named collection, creating the collection if it is new, and "
        "queue it for ingestion (reading, keyword index, embeddings) in the background, "
        "embedded with the request's model preset and key when it sends them. "
        f"Non-PDF content and PDFs over the page limit return 422; files over the size limit "
        f"return 413. A collection embedded with another preset or embedding model returns "
        f"409. {NO_AUTH_NOTE}"
    ),
)
def upload_document(
    request: Request,
    collection: Annotated[str, PathParam(min_length=1, max_length=200)],
    file: Annotated[UploadFile, File()],
    credentials: Annotated[Credentials | None, Depends(request_credentials)],
) -> dict:
    limits: Limits = request.app.state.limits
    engine = request.app.state.engine
    session = current_session(request)
    limits.upload_dir.mkdir(parents=True, exist_ok=True)

    document_id = uuid.uuid4().hex
    fd, tmp_name = tempfile.mkstemp(dir=limits.upload_dir, prefix=".upload-", suffix=".part")
    tmp_path = Path(tmp_name)
    try:
        size = 0
        with os.fdopen(fd, "wb") as out:
            while chunk := file.file.read(CHUNK_BYTES):
                if size == 0 and not chunk.startswith(b"%PDF"):
                    raise HTTPException(422, "file is not a PDF")
                size += len(chunk)
                if size > limits.max_upload_bytes:
                    raise HTTPException(
                        413, f"file is larger than {limits.max_upload_bytes // (1024 * 1024)} MB"
                    )
                out.write(chunk)
        if size == 0:
            raise HTTPException(422, "file is not a PDF")

        try:
            with pymupdf.open(tmp_path, filetype="pdf") as pdf:
                pages = pdf.page_count
        except Exception as exc:
            raise HTTPException(422, "file could not be read as a PDF") from exc
        if pages == 0:
            raise HTTPException(422, "PDF has no pages")
        if pages > limits.max_pdf_pages:
            raise HTTPException(422, f"PDF has {pages} pages; the limit is {limits.max_pdf_pages}")

        filename = display_name(file.filename)
        final_path = stored_path(limits, document_id)
        # Deleting a collection's last document removes the collection, so the collection
        # found here can be gone before the row goes in. The insert then fails on its foreign
        # key before the file moves, and is tried once more against the collection made anew.
        for attempt in range(2):
            collection_id = _upload_collection(request, session, collection, credentials)
            try:
                with engine.begin() as conn:
                    conn.execute(
                        insert(documents).values(
                            id=document_id,
                            collection_id=collection_id,
                            filename=filename,
                            size_bytes=size,
                            page_count=pages,
                        )
                    )
                    conn.execute(
                        insert(ingestion_status).values(
                            document_id=document_id, state="queued", pages_total=pages
                        )
                    )
                    # Inside the transaction: if the rename fails, the row is rolled back.
                    tmp_path.replace(final_path)
                break
            except IntegrityError:
                final_path.unlink(missing_ok=True)
                if attempt or not tmp_path.exists():
                    raise
            except BaseException:
                # The commit failed after the rename: no row points at the file, so remove it.
                final_path.unlink(missing_ok=True)
                raise
    finally:
        tmp_path.unlink(missing_ok=True)

    # In memory only: the worker embeds with them and they are never stored.
    request.app.state.worker.submit(document_id, credentials)
    return {
        "id": document_id,
        "collection": collection,
        "filename": filename,
        "pages": pages,
        "size_bytes": size,
        "status": "queued",
    }


@router.get(
    "/documents/{document_id}/status",
    description=(
        "Where a document's ingestion is: its state (`queued`, `processing`, `ready`, or "
        "`failed` with the reason), how many pages were read, and, once its pages are read, "
        "each page with the method that read it (`text_layer` or `tesseract` from OCR, "
        "`pymupdf` from the text layer fallback) and why OCR failed on it, if it did. Pages "
        f"no method could read are listed under `failures` with the reason. {NO_AUTH_NOTE}"
    ),
)
def document_status(request: Request, document_id: str) -> dict:
    with request.app.state.engine.connect() as conn:
        row = conn.execute(
            select(documents.c.filename, ingestion_status)
            .join(ingestion_status, ingestion_status.c.document_id == documents.c.id)
            .where(documents.c.id == document_id, visible_documents(current_session(request)))
        ).first()
        if row is None:
            raise HTTPException(404, "document not found")
        page_rows = conn.execute(
            _page_status_query().where(page_table.c.document_id == document_id)
        ).all()
    return {"id": document_id, "filename": row.filename, **status_fields(row, page_rows)}


def _page_status_query():
    return select(
        page_table.c.document_id,
        page_table.c.page,
        page_table.c.method,
        page_table.c.ocr_error,
        page_table.c.error,
    ).order_by(page_table.c.document_id, page_table.c.page)


def status_fields(row, page_rows) -> dict:
    """The status of one document from its `ingestion_status` row and its page rows."""
    failures = [
        {"page": p.page, "reason": p.error, "ocr_error": p.ocr_error}
        for p in page_rows
        if p.error is not None
    ]
    return {
        "state": row.state,
        "error": row.error,
        "pages_total": row.pages_total,
        "pages_read": row.pages_read,
        "pages_failed": len(failures),
        "chunks_total": row.chunks_total,
        "chunks_embedded": row.chunks_embedded,
        "updated_at": row.updated_at,
        "pages": [
            {"page": p.page, "method": p.method, "ocr_error": p.ocr_error, "error": p.error}
            for p in page_rows
        ],
        "failures": failures,
    }


@router.get(
    "/collections",
    description=(
        "Every collection by name, each with its documents in upload order. A document has "
        "its display file name, page count, size and, under `status`, the same status fields "
        "as `GET /documents/{document_id}/status`. Deleting a collection's last document "
        "removes the collection, so a listed collection normally has documents. Each "
        "collection names the preset and embedding model it was embedded with (null for the "
        "server's own model; it is asked only with them) and whether it is `read_only`. "
        f"{NO_AUTH_NOTE}"
    ),
)
def list_collections(request: Request) -> list[dict]:
    session = current_session(request)
    with request.app.state.engine.connect() as conn:
        collection_rows = conn.execute(
            select(
                collections.c.id,
                collections.c.name,
                collections.c.session_id,
                collections.c.embedding_preset,
                collections.c.embedding_model,
            )
            .where(collections.c.session_id.in_(visible_owners(session)))
            .order_by(collections.c.name, collections.c.id)
        ).all()
        document_rows = conn.execute(
            select(
                documents.c.id,
                documents.c.collection_id,
                documents.c.filename,
                documents.c.page_count,
                documents.c.size_bytes,
                documents.c.created_at,
                ingestion_status,
            )
            .join(ingestion_status, ingestion_status.c.document_id == documents.c.id)
            .where(visible_documents(session))
            .order_by(documents.c.created_at, documents.c.id)
        ).all()
        page_rows = conn.execute(
            _page_status_query().where(
                page_table.c.document_id.in_(
                    select(documents.c.id).where(visible_documents(session))
                )
            )
        ).all()

    pages_by_document: dict[str, list] = {}
    for p in page_rows:
        pages_by_document.setdefault(p.document_id, []).append(p)
    documents_by_collection: dict[int, list[dict]] = {}
    for d in document_rows:
        documents_by_collection.setdefault(d.collection_id, []).append(
            {
                "id": d.id,
                "filename": d.filename,
                "pages": d.page_count,
                "size_bytes": d.size_bytes,
                "created_at": d.created_at,
                "status": status_fields(d, pages_by_document.get(d.id, [])),
            }
        )
    return [
        {
            "id": c.id,
            "name": c.name,
            "embedding_preset": c.embedding_preset,
            "embedding_model": c.embedding_model,
            # The sample, in a public demo: it can be read and asked, not changed.
            "read_only": c.session_id != session,
            "documents": documents_by_collection.get(c.id, []),
        }
        for c in collection_rows
    ]


@router.get(
    "/documents/{document_id}/pdf",
    response_class=FileResponse,
    responses={
        200: {
            "description": "The PDF",
            "content": {"application/pdf": {"schema": {"type": "string", "format": "binary"}}},
        },
        404: error_response("`document not found`, or `file not found` when its file is gone"),
    },
    description=(
        "The stored PDF, inline (`application/pdf`, `X-Content-Type-Options: nosniff`), for "
        "the browser's PDF viewer. The id is the one the server generated at upload; any "
        f"other id, path-like or not, returns 404. {NO_AUTH_NOTE}"
    ),
)
def document_pdf(request: Request, document_id: str) -> FileResponse:
    with request.app.state.engine.connect() as conn:
        filename = conn.execute(
            select(documents.c.filename).where(
                documents.c.id == document_id, visible_documents(current_session(request))
            )
        ).scalar()
    if filename is None:
        raise HTTPException(404, "document not found")
    # The id matched a row, so it is one we generated and safe in a path.
    path = stored_path(request.app.state.limits, document_id)
    if not path.is_file():
        raise HTTPException(404, "file not found")
    return FileResponse(
        path,
        media_type="application/pdf",
        filename=filename,
        content_disposition_type="inline",
        headers={"X-Content-Type-Options": "nosniff"},
    )


@router.get(
    "/documents/{document_id}/pages/{page}",
    description=(
        "One page's stored text (pages count from 1): the exact text that chunk offsets and "
        "so citations index into, with the method that read it. A page no method could read "
        "has `text` null and the reason in `error`. A page outside the document returns 404; "
        f"a page the worker has not read yet returns 409. {NO_AUTH_NOTE}"
    ),
)
def document_page(request: Request, document_id: str, page: int) -> dict:
    with request.app.state.engine.connect() as conn:
        page_count = conn.execute(
            select(documents.c.page_count).where(
                documents.c.id == document_id, visible_documents(current_session(request))
            )
        ).scalar()
        if page_count is None:
            raise HTTPException(404, "document not found")
        if not 1 <= page <= page_count:
            raise HTTPException(404, "page not found")
        row = conn.execute(
            select(page_table.c.text, page_table.c.method, page_table.c.error).where(
                page_table.c.document_id == document_id, page_table.c.page == page
            )
        ).first()
    if row is None:
        raise HTTPException(409, "page has not been read yet")
    return {
        "document_id": document_id,
        "page": page,
        "text": row.text,
        "method": row.method,
        "error": row.error,
    }


@router.delete(
    "/documents/{document_id}",
    status_code=204,
    responses={
        204: DELETED,
        403: error_response("`The sample collection is read-only`"),
        404: error_response("`document not found`"),
    },
    description=(
        "Delete a document: its stored file, its row, and (by foreign-key cascade) every row "
        "derived from it. When it was the last document of its collection, the collection is "
        f"removed too. {NO_AUTH_NOTE}"
    ),
)
def delete_document(request: Request, document_id: str) -> Response:
    limits: Limits = request.app.state.limits
    session = current_session(request)
    with request.app.state.engine.begin() as conn:
        owner = conn.execute(
            select(collections.c.session_id)
            .join(documents, documents.c.collection_id == collections.c.id)
            .where(documents.c.id == document_id, visible_documents(session))
        ).scalar()
        if owner is None:
            raise HTTPException(404, "document not found")
        require_owner(session, owner)
        collection_id = conn.execute(
            delete(documents)
            .where(documents.c.id == document_id)
            .returning(documents.c.collection_id)
        ).scalar()
        if collection_id is None:
            raise HTTPException(404, "document not found")
        _delete_collection_if_empty(conn, collection_id)
        # The id matched a row, so it is one we generated and safe in a path. Unlinking inside
        # the transaction means a file that cannot be removed leaves its row in place too.
        stored_path(limits, document_id).unlink(missing_ok=True)
    return Response(status_code=204)


def _delete_collection_if_empty(conn: Connection, collection_id: int) -> bool:
    """Delete the collection when it has no documents; True when it was deleted.

    The row lock waits for an upload that is inserting into the collection right now, and
    the `NOT EXISTS` then sees its document, so a concurrent upload keeps the collection.
    """
    conn.execute(
        select(collections.c.id).where(collections.c.id == collection_id).with_for_update()
    )
    return bool(
        conn.execute(
            delete(collections).where(
                collections.c.id == collection_id,
                ~exists().where(documents.c.collection_id == collection_id),
            )
        ).rowcount
    )


@router.delete(
    "/collections/{collection}",
    status_code=204,
    responses={
        204: DELETED,
        403: error_response("`The sample collection is read-only`"),
        404: error_response("`collection not found`"),
        409: error_response("`collection is not empty`"),
    },
    description=(
        "Delete an empty collection by name. A collection that still has documents is never "
        "deleted here (409 `collection is not empty`): delete its documents first, and the "
        f"last delete removes the collection. An unknown name returns 404. {NO_AUTH_NOTE}"
    ),
)
def delete_collection(
    request: Request, collection: Annotated[str, PathParam(min_length=1, max_length=200)]
) -> Response:
    session = current_session(request)
    with request.app.state.engine.begin() as conn:
        found = find_collection(conn, session, collection)
        if found is None:
            raise HTTPException(404, "collection not found")
        require_owner(session, found.session_id)
        if not _delete_collection_if_empty(conn, found.id):
            raise HTTPException(409, "collection is not empty")
    return Response(status_code=204)
