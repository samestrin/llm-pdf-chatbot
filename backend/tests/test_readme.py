import re
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
README = (REPO / "README.md").read_text()


def corpus() -> str:
    parts = [(REPO / "docker-compose.yml").read_text(), (REPO / ".env.example").read_text()]
    for root in ("backend/app", "scripts"):
        for p in (REPO / root).rglob("*"):
            if p.is_file() and p.suffix in {".py", ".sh"}:
                parts.append(p.read_text())
    return "\n".join(parts)


def test_every_env_var_named_in_the_readme_exists():
    text = corpus()
    names = set(re.findall(r"`([A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+)`", README))
    assert names
    missing = sorted(n for n in names if not re.search(rf"\b{n}\b", text))
    assert not missing, missing


def test_every_documented_command_exists():
    compose = (REPO / "docker-compose.yml").read_text()
    assert "services:" in compose
    scripts = set(re.findall(r"\./(scripts/[\w.-]+)", README))
    assert scripts
    for s in scripts:
        assert (REPO / s).is_file(), s
    pkg = (REPO / "frontend/package.json").read_text()
    for name in re.findall(r"npm run ([\w:-]+)", README):
        assert f'"{name}"' in pkg, name
    assert "docker compose up" in README
    assert (REPO / ".env.example").is_file() and "cp .env.example .env" in README


def test_every_image_link_resolves():
    links = re.findall(r"!\[[^\]]*\]\(([^)]+)\)", README)
    assert len(links) >= 3
    for link in links:
        assert not link.startswith("http"), link
        assert (REPO / link).is_file(), link


# `npm run capture:readme` writes the screenshots from the fixture-backed page; the demo GIF
# is a real session written only by `npm run capture:live`. A doc that sends a reader to
# capture:readme for the GIF would have them overwrite the live GIF with a mocked one.
CAPTURE_COMMAND = re.compile(r"capture:(?:readme|live)")
GIF = re.compile(r"\bGIF\b|demo\.gif", re.IGNORECASE)


def gif_attributed_to(text: str) -> set[str]:
    """The capture commands named in the same clause as the GIF."""
    clauses = re.split(r"(?<=[.;:])\s|\n\n", text)
    return {cmd for c in clauses if GIF.search(c) for cmd in CAPTURE_COMMAND.findall(c)}


def test_gif_attribution_is_read_per_clause():
    old = "The screenshots and GIF in `docs/img/` are generated by `npm run capture:readme`."
    assert gif_attributed_to(old) == {"capture:readme"}
    new = (
        "`npm run capture:readme` writes the screenshots (PNGs); "
        "`npm run capture:live` records the GIF."
    )
    assert gif_attributed_to(new) == {"capture:live"}


@pytest.mark.parametrize("page", ["README.md", "docs/development.md"])
def test_docs_say_capture_live_makes_the_gif_and_capture_readme_the_pngs(page):
    text = (REPO / page).read_text()
    assert gif_attributed_to(text) == {"capture:live"}
    assert re.search(r"capture:readme`[^.;]*\bPNGs?\b|\bPNGs?\b[^.;]*capture:readme`", text)


